; ---------------- v0.6 JUNO page ----------------
; Fixed partial roles, like the Juno's one DCO: P1 = SAW, P2 = PULSE, P3 = SUB OSC (square, -1 oct), P4 = DETUNE (a
; detuned copy of P1 = the chorus). A level of 0 switches that partial off (common 0x0C), so unused partials cost no
; polyphony. MAKE JUNO turns the tone into that voice: P1's filter / envelope / LFO copied to all four, S+S S+S.

; A = value of the JUNO item IT (X = IT)
jget:   ldaa IT_AUX,x
        beq jg0                 ; MAKE: nothing to show
        cmpa #J_PWM
        bcc jg4
        deca                    ; ops 1-3: level of partial op-1
        jmp jlev
jg0:    clra
        rts
jg4:    bne jg5
        ldaa #1                 ; PW MODE: P2's pulse width -> pwtab step
        jsr pbase
        ldaa WG_PW,x
        ldx #pwtab
        clrb
jg4a:   cmpa 1,x
        bcs jg4b
        inx
        incb
        cmpb #NPW-1
        bne jg4a
jg4b:   tba
        rts
jg5:    cmpa #J_DET
        bne jg6
        ldaa WORK+$0C           ; DETUNE: 0 = P4 off, else P4's fine - 50 (cents)
        anda #$08
        beq jg0
        ldaa #3
        jsr pbase
        ldaa WG_FINE,x
        suba #50
        bcc jg5a
        clra
jg5a:   rts
jg6:    cmpa #J_PWMD
        beq jg7
        ldaa WORK+14+WG_COARSE  ; RANGE from P1
        jmp jrng
jg7:    ldaa WORK+14+58+WG_PCM  ; PWM: P2's byte $71-$7A = depth 1-10, anything else = off
        tab
        andb #$F0
        cmpb #$70
        bne jg7z
        anda #$0F
        cmpa #10
        bls jg7a
jg7z:   clra
jg7a:   rts

; A = partial 0-3 -> A = its level, 0 when it is switched off
jlev:   psha
        ldx #pmask
        tab
        abx
        ldab 0,x
        andb WORK+$0C
        pula
        tstb
        beq jl0
        jsr pbase
        ldaa TVA_LEVEL,x
        rts
jl0:    clra
        rts

; A = coarse -> A = RANGE step 0-3 (16' 8' 4' 2' = coarse 24 36 48 60)
jrng:   clrb
jr_a:   cmpa #30
        bcs jr_b
        cmpb #3
        beq jr_b
        suba #12
        incb
        bra jr_a
jr_b:   tba
        rts

jchg:   jsr getval              ; NEWV = the value moved by the dial
        psha
        ldx IT
        ldab IT_MAX,x
        stab MAXV
        ldab IT_AUX,x
        stab JOP
        pulb
        jsr addclamp
        stab NEWV
        ldab JOP
        bne jc1
        jmp jmake
jc1:    cmpb #J_PWM
        bcs jsetlv
        beq jsetpw
        cmpb #J_DET
        bne jc_pm
        jmp jsetdt
jc_pm:  cmpb #J_PWMD
        bne jc_rg
        jmp jsetpm
jc_rg:  jmp jsetrg

jsetlv: decb                    ; SAW / PULSE / SUB level
        tba
        jsr jlevset
        ldaa JOP
        cmpa #1
        bne jx
        ldaa WORK+$0C           ; SAW: a detuned P4 follows its level
        anda #$08
        beq jx
        ldaa NEWV
        beq jx
        ldaa #3
        jsr pbase
        ldaa NEWV
        ldab #TVA_LEVEL
        jsr putb
jx:     jmp leds

; A = partial 0-3: level NEWV, 0 = switch it off
jlevset: psha
        ldx #pmask
        tab
        abx
        ldaa 0,x
        staa JV
        pula
        ldab NEWV
        beq jl_off
        jsr pbase
        ldaa NEWV
        ldab #TVA_LEVEL
        jsr putb
        ldaa WORK+$0C
        oraa JV
        bra jl_m
jl_off: ldaa JV
        coma
        anda WORK+$0C
jl_m:   ldab #$0C               ; common byte B = A
        clr IDXB
        clr IDXB+1
        ldx #WORK
        jmp putb

jsetpw: ldx #pwtab              ; P2 pulse width
        ldab NEWV
        abx
        ldaa 0,x
        staa JC
        ldaa #1
        jsr pbase
        ldaa JC
        ldab #WG_PW
        jsr putb
        jmp leds

; v0.11 PWM: P2's PCM-wave byte = $70 + depth (0 = 0 = off). A synth partial ignores that byte; IC28 v8 reads it.
jsetpm: ldaa NEWV
        beq jp_w
        adda #$70
jp_w:   psha
        ldaa #1
        jsr pbase
        pula
        ldab #WG_PCM
        jsr putb
        jmp leds

jsetdt: ldaa NEWV               ; DETUNE 0 = P4 off
        bne jd_on
        ldaa #3
        jsr jlevset
        jmp leds
jd_on:  ldaa #3                 ; P4 = P1's oscillator, NEWV cents sharp, P1's level
        jsr pbase
        ldaa WORK+14+WG_WAVE
        ldab #WG_WAVE
        jsr putb
        ldaa WORK+14+WG_COARSE
        ldab #WG_COARSE
        jsr putb
        ldaa NEWV
        adda #50
        ldab #WG_FINE
        jsr putb
        ldaa WORK+14+TVA_LEVEL
        staa NEWV
        ldaa #3
        jsr jlevset
        jmp leds

jsetrg: ldab NEWV               ; RANGE: coarse 24 + 12 * step on all, the SUB an octave lower
        ldaa #12
        mul
        addb #24
        stab JC
        clra
jr_lp:  staa JV
        jsr pbase
        ldaa JC
        ldab JV
        cmpb #2
        bne jr1
        suba #12
jr1:    ldab #WG_COARSE
        jsr putb
        ldaa JV
        inca
        cmpa #4
        bne jr_lp
        jmp leds

jmake:  tst DELTA               ; MAKE JUNO: dial right
        bgt jm_go
        rts
jm_go:
        ldaa WORK+14+TVA_LEVEL  ; v0.12: P1 silent (e.g. a PWM-only patch) -> level 100, else the Juno is silent
        bne jm_lv
        ldaa #100
        staa WORK+14+TVA_LEVEL
jm_lv:  ldx #WORK+14            ; P1 -> P2, P3, P4
        ldy #WORK+14+58
jm_cp:  ldaa 0,x
        staa 0,y
        inx
        iny
        cpy #WORK+246
        bne jm_cp
        ldaa WORK+14+WG_COARSE  ; keep P1's octave, snapped to a RANGE step
        jsr jrng
        ldab #12
        mul
        addb #24
        stab JC
        ldx #WORK+14
        ldy #jrole
jm_p:   ldaa 0,y
        staa WG_WAVE,x
        ldaa JC
        adda 1,y
        staa WG_COARSE,x
        ldaa 2,y
        staa WG_FINE,x
        clr WG_PW,x
        clr WG_PCM,x            ; v0.11: no PWM after MAKE JUNO (and no stray byte)
        ldaa #11                ; key follow 1
        staa WG_KEYF,x
        ldaa #1                 ; bender on
        staa WG_BEND,x
        ldaa #8                 ; pitch env depth 8 (about 1 octave at AMOUNT 50), levels flat = no pitch env
        staa PE_DEPTH,x
        ldaa #50
        staa PE_L0,x
        staa PE_L0+1,x
        staa PE_L0+2,x
        staa PE_L0+3,x
        staa PE_L0+4,x
        ldab #58
        abx
        iny
        iny
        iny
        cpy #jrole+12
        bne jm_p
        clr WORK+$0A            ; S+S, S+S
        clr WORK+$0B
        ldaa #$01               ; SAW only: dial PULSE / SUB / DETUNE up to add them
        staa WORK+$0C
        jsr dtall
        jmp leds

; one DT1 with the whole tone (246 bytes from timbre temp 02 00 00), like the stock boot sends tones
dtall:  ldaa #$F0
        jsr SENDCK
        ldaa #$41
        jsr SENDCK
        ldaa DEV
        jsr SENDCK
        ldaa #$16
        jsr SENDCK
        ldaa #$12
        jsr SENDCK
        ldaa #$02
        staa SUM
        jsr SENDCK
        clra
        jsr SENDCK
        clra
        jsr SENDCK
        ldy #WORK
da_lp:  ldaa 0,y
        adda SUM
        staa SUM
        ldaa 0,y
        jsr SENDCK              ; keeps Y
        iny
        cpy #WORK+246
        bne da_lp
        ldaa SUM
        nega
        anda #$7F
        jsr SENDCK
        ldaa #$F7
        jmp SENDCK

