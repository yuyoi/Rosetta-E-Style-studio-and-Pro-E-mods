; Rosetta OS PRO-E v0.5: SYNTH EDIT, Juno-style macro editing of the CK-34 LA tone, menus like the D-70 Rosetta OS.
; CURSOR on the main screen opens it (v0.4b's TRANSPOSE + MELODY INT combo lost to the TRANSPOSE hold page). Levels: 0 = page list, 1 = parameter list, 2 = editing a value.
; TEMPO dial scrolls / changes, CURSOR = enter, PARAMETER = back (out of SYNTH EDIT from the page list),
; NUMBER 1-8 = jump to page 1-8 (v0.5b: the rows were swapped). v0.5c: the dial accelerates while editing a value. BANK 1-4 = select partial 1-4 (macros edit only it;
; press it again = partial on/off), BANK 5 = all partials. The 4 tempo LEDs show it (red = P1, greens = P2-P4): lit = selected, blinking = switched off.
; Code lives in IC7 upper half bank 5 (PA6 = 1), tables are generated by build_v04b.py.
;
; On entry the part's timbre temp (246 bytes) is read back from the CK-34 with RQ1 into WORK (SCI receiver on
; only while waiting). Every edit changes WORK and sends one DT1 per changed byte, so the CK-34 hears it at once.
; Macro parameters act on every active partial: REL items move each partial's value by the dial step (the tone's
; own balance stays), ABS items set the same value on all of them.

; ---- stock addresses ----
KEYCODE  = $2648
KEYSTATE = $245F        ; byte 1 bit 0 = TRANSPOSE ($08), bit 1 = MELODY INT ($09)
LEDS0    = $0B          ; $0B.4/.5 = MIDI / PARAMETER menu open
MENUS    = $5E          ; $5E.6 = REVERB menu (page $0D, borrowed while editing)
DEMO     = $5D          ; bit 7 = demo playing
TIMEOUT  = $19          ; bit 7 = no message timeout
TRHOLD   = $2D64        ; TRANSPOSE hold timer
PAGEID   = $2662        ; page handler = $FA78 + 3 * (page - $0C)
DLOW     = $51
DHIGH    = $52
DVAL     = $53
DSTEP    = $54
DCNT     = $55
DLOCK    = $2674
LINE1P   = $2665
LINE2P   = $2667
WINFULL  = $D582
DRAW     = $D5AB
SENDCK   = $E82E        ; A -> CK-34 TX ring (keeps A, clobbers B and X)
SCCR2    = $102D
SCSR     = $102E
SCDR     = $102F
K_PARAM  = $05
K_CURSOR = $5D
K_BANK1  = $38
K_NUM1   = $40          ; NUMBER 1-6 = $40-$45
K_NUM7   = $58          ; NUMBER 7-8 = $58-$59
BEAT     = $10          ; LED byte: bits 3..0 = tempo LEDs 1 (red) .. 4
BEAT2    = $16          ; the same LEDs in the alternate (blink) frame

T_NUM    = 0
T_SGN    = 1
T_LIST   = 2
T_PCM    = 3
T_WAVE   = 4
T_PART   = 5
T_CLIST  = 6            ; common byte, list (structure)
T_RING   = 7            ; ring mod of a structure byte, OFF / ON
F_ABS    = 1
F_FIXP   = 2            ; item edits partial IT_AUX (1-4) only, whatever is selected
IT_TYPE  = 0
IT_MAX   = 1
IT_AUX   = 2
IT_FLAGS = 3
IT_N     = 4
IT_OFF   = 5
IT_LABEL = 11
PG_FLAGS = 11
PG_N     = 12
PG_IDX   = 13

        org CODE
        jmp entry               ; $A000 = ENTRY: from the RAM trampoline
        jmp boot8               ; $A003: from BOOTCOPY in IC4. Fixed, so later SYNTH builds only change IC7
; entry from the RAM trampoline: A = 0 key event (B = $80 press / 0 release), A = 1 page-$0D tick
; return C = 1: handled, C = 0: run the stock code
entry:  tsta
        bne tick
        ldaa EDIT
        bne inedit
        tstb
        bpl pass
        ldaa KEYCODE            ; CURSOR opens it: no LED, and stock only uses it inside its menus
        cmpa #K_CURSOR
        bne pass
tryent: ldaa LEDS0              ; only from the main screen: no menu, no demo
        anda #$30
        bne pass
        ldaa MENUS
        anda #$7E
        bne pass
        ldaa DEMO
        bmi pass
        jsr enter
        sec
        rts
pass:   clc
        rts
inedit: ldaa MENUS              ; something else closed our page: let go
        anda #$40
        bne ie_ok
        clr EDIT
        clc
        rts
ie_ok:  tstb
        bpl eat                 ; releases are swallowed
        ldaa KEYCODE
        cmpa #K_PARAM
        bne ie1
        jsr k_back
        bra eat
ie1:    cmpa #K_CURSOR
        bne ie2
        jsr k_enter
        bra eat
ie2:    cmpa #K_BANK1           ; BANK 1-4 = partials, BANK 5 = all
        bcs eat
        cmpa #K_BANK1+4
        bhi ie3
        suba #K_BANK1
        jsr k_num
        bra eat
ie3:    cmpa #K_NUM1            ; NUMBER 1-6 ($40-$45) + 7-8 ($58-$59) = pages 1-8
        bcs eat
        cmpa #K_NUM1+5
        bhi ie4
        suba #K_NUM1
        bra ie5
ie4:    cmpa #K_NUM7
        bcs eat
        cmpa #K_NUM7+1
        bhi eat
        suba #K_NUM7-6
ie5:    jsr k_bank
eat:    sec
        rts

tick:   ldaa EDIT
        beq pass                ; the real REVERB menu
        jsr leds                ; every 20 ms: the tempo code may have drawn a beat over them
        ldaa DVAL
        suba #50
        beq t_done
        staa DELTA
        ldaa #50
        staa DVAL
        jsr k_dial
t_done: sec
        rts

; ---------------- open / close ----------------
enter:  ldaa #1
        staa EDIT
        nop                     ; (v0.4c: clr TRHOLD here armed the TRANSPOSE hold timer: $00 = fire now, $FF = idle)
        nop
        nop
        bset MENUS,#$40         ; page $0D: dial routed to our tick
        bset TIMEOUT,#$80       ; no message timeout
        ldaa #$0D
        staa PAGEID
        ldd #$0164              ; dial range 0..100, centre 50
        std DLOW
        clr LVL
        clr SEL
        clr ROW
        clr SELP                ; all partials
        ldaa BEAT               ; keep the tempo LEDs as they were
        anda #$0F
        staa SAV10
        ldaa BEAT2
        anda #$0F
        staa SAV16
        jsr dialnav
        jsr readtone
        jsr leds
        jmp redraw

leave:  tpa                     ; tempo LEDs back
        psha
        sei
        ldaa BEAT
        anda #$F0
        oraa SAV10
        staa BEAT
        ldaa BEAT2
        anda #$F0
        oraa SAV16
        staa BEAT2
        pula
        tap
        clr EDIT
        bclr MENUS,#$40
        clr TIMEOUT             ; next tick: stock timeout path restores the main screen + tempo dial
        ldaa #$0C
        staa DLOCK
        rts

dialnav: ldaa #8                ; pulses per step: lists like the stock MIDI menu
        bra dset
dialval: ldaa #2                ; values like the tempo dial
dset:   staa DSTEP
        staa DCNT
        ldaa #50
        staa DVAL
        ldaa #$0C
        staa DLOCK              ; 240 ms dial lock like the stock menus
        rts

; ---------------- keys ----------------
k_back: ldaa LVL                ; PARAMETER: one level up
        beq leave
        deca
        staa LVL
        jsr dialnav
        jmp redraw

k_enter: ldaa LVL               ; CURSOR: one level down (level 2 -> back to 1)
        bne ke1
        clr ROW
        ldaa #1
        staa LVL
        jsr pageptr
        ldaa PG_FLAGS,x         ; LIVE page: straight into editing
        anda #1
        beq ke_nav
ke_val: ldaa #2
        staa LVL
        jsr dialval
        jmp redraw
ke1:    cmpa #1
        beq ke_val
        ldaa #1
        staa LVL
ke_nav: jsr dialnav
        jmp redraw

k_bank: cmpa #NPAGES            ; BANK n: page n
        bcc kb_x
        staa SEL
        clr LVL
        bra k_enter
kb_x:   rts

; NUMBER 1-4 (A = 0-3): select that partial, or switch it on/off if it is selected already. NUMBER 5 (A = 4): all.
k_num:  cmpa #4
        bne kn1
        clr SELP
        bra kn_x
kn1:    inca
        cmpa SELP
        beq kn_mute
        staa SELP
        bra kn_x
kn_mute: deca                   ; toggle this partial's bit in the timbre's partial-mute byte (common 0x0C)
        ldx #pmask
        tab
        abx
        ldab 0,x
        eorb WORK+$0C
        tba
        clrb
        stab IDXB
        stab IDXB+1
        ldx #WORK
        ldab #$0C
        jsr putb
kn_x:   jsr leds
        jmp redraw

; tempo LEDs = partials: red = P1 .. green 3 = P4. Lit in both frames = selected and on, frame 1 only = blinking = off.
; All selected: every partial is shown. One selected: only that one.
leds:   ldaa WORK+$0C
        anda #$0F
        staa TMP
        clr LF1
        clr LF2
        clrb
ld_lp:  stab PNUM
        ldaa SELP
        beq ld_sh
        deca
        cba
        bne ld_nx
ld_sh:  ldx #lmask
        abx
        ldaa 0,x
        staa LB
        oraa LF1
        staa LF1
        ldx #pmask
        ldab PNUM
        abx
        ldaa 0,x
        anda TMP
        beq ld_nx
        ldaa LF2
        oraa LB
        staa LF2
ld_nx:  ldab PNUM
        incb
        cmpb #4
        bne ld_lp
        tpa
        psha
        sei
        ldaa BEAT
        anda #$F0
        oraa LF1
        staa BEAT
        ldaa BEAT2
        anda #$F0
        oraa LF2
        staa BEAT2
        pula
        tap
        rts

k_dial: ldaa LVL
        bne kd1
        ldaa #NPAGES-1
        staa MAXV
        ldab SEL
        jsr addclamp
        stab SEL
        jmp redraw
kd1:    cmpa #1
        bne kd2
        jsr pageptr
        ldaa PG_N,x
        deca
        staa MAXV
        ldab ROW
        jsr addclamp
        stab ROW
        jmp redraw
kd2:    jsr accel
        jsr change
        jmp redraw

; value editing only: DELTA = d + sign(d) * d*d/4 (the D-70 value dial). Slow = 1 per click, a fast spin jumps far.
accel:  ldaa DELTA
        bpl ax1
        nega
ax1:    staa ACC                ; |d|
        tab
        mul                     ; |d|^2
        lsrd
        lsrd                    ; /4
        tsta
        bne ax_big
        addb ACC
        bcs ax_big
        cmpb #100
        bls ax2
ax_big: ldab #100
ax2:    tst DELTA
        bpl ax3
        negb
ax3:    stab DELTA
        rts

; B = clamp(B + DELTA, 0, MAXV); DELTA is signed
addclamp:
        clra
        std T16
        ldab DELTA
        clra
        tstb
        bpl ac1
        coma
ac1:    addd T16
        bmi ac0
        tsta
        bne acm
        cmpb MAXV
        bhi acm
        rts
ac0:    clrb
        rts
acm:    ldab MAXV
        rts

; ---------------- tables ----------------
pageptr: ldaa SEL               ; X = page record
        ldab #PGSIZE
        mul
        addd #PAGES
        xgdx
        rts

itemptr: jsr pageptr            ; IT = X = item record of (SEL, ROW)
        ldab ROW
        abx
        ldaa PG_IDX,x
        ldab #20
        mul
        addd #ITEMS
        std IT
        xgdx
        rts

; MASK = partials the item IT edits, REFP = the one shown. Fixed-partial item: that one. One partial selected: that one
; (even when switched off). All: the partials that are on (none on = all four), shown = the lowest.
actmask: ldx IT
        ldab IT_FLAGS,x
        andb #F_FIXP
        beq am_sel
        ldaa IT_AUX,x
        bra am_one
am_sel: ldaa SELP
        beq am_all
am_one: deca
        staa REFP
        ldx #pmask
        tab
        abx
        ldaa 0,x
        staa MASK
        rts
am_all: ldaa WORK+$0C
        anda #$0F
        bne am1
        ldaa #$0F
am1:    staa MASK
        clrb
am2:    lsra
        bcs am3
        incb
        bra am2
am3:    stab REFP
        rts

; A = partial -> X = its 58 bytes in WORK, IDXB = its timbre-temp index
pbase:  ldab #58
        mul
        addd #14
        std IDXB
        addd #WORK
        xgdx
        rts

; next active partial after PNUM: C = 0 and X / IDXB set, C = 1 when done
pnext:  ldaa PNUM
        cmpa #4
        bcc pn_end
        inc PNUM
        ldab MASK
        tsta
pn_sh:  beq pn_t
        lsrb
        deca
        bra pn_sh
pn_t:   lsrb
        bcc pnext
        ldaa PNUM
        deca
        jsr pbase
        clc
        rts
pn_end: sec
        rts

; A = value of the item IT, read from the reference partial
getval: ldx IT
        ldab IT_TYPE,x
        cmpb #T_PART
        bne gv1
        ldaa PARTIX
        rts
gv1:    cmpb #T_CLIST           ; common byte: the value itself
        bne gv1r
        ldab IT_OFF,x
        ldx #WORK
        abx
        ldaa 0,x
        rts
gv1r:   cmpb #T_RING            ; ring mod OFF / ON of a structure byte
        bne gv1p
        ldab IT_OFF,x
        ldx #WORK
        abx
        ldab 0,x
        andb #$0F
        ldx #ringon
        abx
        ldaa 0,x
        rts
gv1p:   jsr actmask
        ldaa REFP
        jsr pbase
        ldy IT
        ldab IT_TYPE,y
        cmpb #T_PCM
        bne gv2
        ldaa 4,x                ; WG waveform bit 1 = PCM bank
        anda #2
        asla
        asla
        asla
        asla
        asla
        asla
        oraa 5,x
        rts
gv2:    cmpb #T_WAVE
        bne gv3
        ldaa 4,x                ; bit 0 = SQUARE / SAW
        anda #1
        rts
gv3:    ldab IT_OFF,y
        abx
        ldaa 0,x
        rts

; ---------------- editing ----------------
change: jsr itemptr
        ldab IT_TYPE,x
        cmpb #T_PART
        bne ch1
        ldaa #2
        staa MAXV
        ldab PARTIX
        jsr addclamp
        cmpb PARTIX
        beq ch_x
        stab PARTIX
        jsr readtone
        jmp leds
ch_x:   rts
ch1:    cmpb #T_CLIST
        bne ch2
        jsr getval              ; structure: one common byte, 0..max
        ldx IT
        ldab IT_MAX,x
        stab MAXV
        tab
        jsr addclamp
        tba
        ldx IT
        ldab IT_OFF,x
        bra ch_com
ch2:    cmpb #T_RING
        bne ch3
        ldab IT_OFF,x           ; dial up = ring on, down = ring off: swap to the matching structure
        stab OFFS
        ldx #WORK
        abx
        ldab 0,x
        cmpb #12
        bhi ch_x
        stab TMP
        ldx #ringon
        abx
        ldaa 0,x
        ldab DELTA
        bmi cr_off
        tsta
        bne ch_x                ; already on
        bra cr_sw
cr_off: tsta
        beq ch_x                ; already off
cr_sw:  ldx #ringtog
        ldab TMP
        abx
        ldaa 0,x
        cmpa TMP
        beq ch_x                ; no partner structure (S&P / S*P)
        ldab OFFS
ch_com: psha                    ; A = value, B = common offset: store + DT1
        clra
        staa IDXB
        staa IDXB+1
        pula
        ldx #WORK
        jsr putb
        jmp leds
ch3:    jsr getval              ; A = current value (sets MASK)
        ldx IT
        ldab IT_FLAGS,x
        andb #F_ABS
        beq ch_rel
        ldab IT_MAX,x           ; ABS: one new value for every active partial
        stab MAXV
        tab
        jsr addclamp
        stab NEWV
        clr PNUM
ca_lp:  jsr pnext
        bcs ch_rx
        jsr setabs
        bra ca_lp
ch_rel: clr KIX                 ; REL: every offset of the item, every active partial, moved by DELTA
cr_k:   ldx IT
        ldab KIX
        cmpb IT_N,x
        bcc ch_rx
        abx
        ldab IT_OFF,x
        stab OFFS
        ldx #PMAX
        abx
        ldaa 0,x
        staa MAXV
        clr PNUM
cr_p:   jsr pnext
        bcs cr_nk
        stx PB2
        ldab OFFS
        abx
        ldab 0,x
        jsr addclamp
        tba
        ldx PB2
        ldab OFFS
        jsr putb
        bra cr_p
cr_nk:  inc KIX
        bra cr_k
ch_rx:  rts

; X = partial, IDXB = its index: write NEWV the item's way
setabs: ldy IT
        ldab IT_TYPE,y
        cmpb #T_PCM
        bne sa1
        ldaa NEWV               ; value bit 7 -> waveform bit 1 (bank), bits 0-6 -> PCM wave
        anda #$80
        lsra
        lsra
        lsra
        lsra
        lsra
        lsra
        staa TMP
        ldaa 4,x
        anda #$FD
        oraa TMP
        ldab #4
        jsr putb
        ldaa NEWV
        anda #$7F
        ldab #5
        jmp putb
sa1:    cmpb #T_WAVE
        bne sa2
        ldaa 4,x
        anda #$FE
        oraa NEWV
        ldab #4
        jmp putb
sa2:    ldab IT_OFF,y
        ldaa NEWV
                                ; falls into putb
; A = value, B = offset in the partial X: store it and send it if it changed (X kept)
putb:   stx PB
        abx
        cmpa 0,x
        beq pb_same
        staa 0,x
        staa VAL
        clra
        addd IDXB
        std IDX
        jsr dt1
pb_same: ldx PB
        rts

; DT1 of one byte: timbre temp index IDX = VAL, to the part's channel
dt1:    ldaa #$F0
        jsr SENDCK
        ldaa #$41
        jsr SENDCK
        ldaa DEV
        jsr SENDCK
        ldaa #$16
        jsr SENDCK
        ldaa #$12
        jsr SENDCK
        ldaa #$02
        staa SUM
        jsr SENDCK
        ldd IDX                 ; address mid = IDX >> 7
        asld
        staa TMP
        adda SUM
        staa SUM
        ldaa TMP
        jsr SENDCK
        ldaa IDX+1              ; address lo = IDX & $7F
        anda #$7F
        staa TMP
        adda SUM
        staa SUM
        ldaa TMP
        jsr SENDCK
        ldaa VAL
        adda SUM
        staa SUM
        ldaa VAL
        jsr SENDCK
        ldaa SUM                ; Roland checksum
        nega
        anda #$7F
        jsr SENDCK
        ldaa #$F7
        jmp SENDCK

; ---------------- read the tone back (RQ1) ----------------
readtone:
        ldx #devtab
        ldab PARTIX
        abx
        ldaa 0,x
        staa DEV
        ldx #SCCR2
        bset 0,x,#$04           ; receiver on
        ldaa SCSR               ; flush
        ldaa SCDR
        ldaa SCSR
        ldaa SCDR
        ldx #rq1
rt_s:   stx PB
        ldaa 0,x
        cmpa #$FF
        bne rt_s1
        ldaa DEV
rt_s1:  jsr SENDCK
        ldx PB
        inx
        cpx #rq1+13
        bne rt_s
        clr VALID
        ldab #40                ; up to 40 stray bytes before the F0
rt_f0:  pshb
        jsr rxbyte
        pulb
        bcs rt_fail
        cmpa #$F0
        beq rt_hd
        decb
        bne rt_f0
        bra rt_fail
rt_hd:  ldx #rphdr
rt_h1:  stx PB
        jsr rxbyte
        bcs rt_fail
        ldx PB
        ldab 0,x
        cmpb #$FF
        bne rt_h2
        ldab DEV
rt_h2:  cba
        bne rt_fail
        inx
        cpx #rphdr+7
        bne rt_h1
        ldaa #$02
        staa SUM
        ldx #WORK
rt_d:   stx PB
        jsr rxbyte
        bcs rt_fail
        tsta
        bmi rt_fail
        ldx PB
        staa 0,x
        adda SUM
        staa SUM
        inx
        cpx #WORK+246
        bne rt_d
        jsr rxbyte              ; checksum
        bcs rt_fail
        adda SUM
        anda #$7F
        bne rt_fail
        jsr rxbyte              ; F7
        bcs rt_fail
        cmpa #$F7
        bne rt_fail
        inc VALID
        bra rt_end
rt_fail: ldx #DEFTONE           ; no reply: edit a known tone instead of garbage
        ldy #WORK
rt_cp:  ldaa 0,x
        staa 0,y
        inx
        iny
        cpy #WORK+246
        bne rt_cp
rt_end: ldx #SCCR2
        bclr 0,x,#$04           ; receiver off again (stock: TX only)
        rts

; A = next received byte, C = 1 on timeout (about 0.5 s)
rxbyte: ldx #0
rx_lp:  ldaa SCSR
        bita #$20
        bne rx_got
        dex
        bne rx_lp
        sec
        rts
rx_got: ldaa SCDR
        clc
        rts

; ---------------- screen ----------------
redraw: ldaa LVL
        bne rd1
        ldx #ttl_ok             ; page list: "SYNTH EDIT  SOLO" / " FILTER     4/9"
        ldaa VALID
        bne rd0
        ldx #ttl_nr
rd0:    ldy #LINE1
        ldab #12
        jsr copyn
        jsr partnm
        ldy #LINE2              ; "PCM WAVE    2/10"
        jsr pageptr
        ldab #11
        jsr copyn
        ldaa #' '
        staa 0,y
        ldaa SEL
        inca
        cmpa #10
        bcs rd0a
        suba #10
        ldab #'1'
        stab 0,y
rd0a:   adda #'0'
        staa 1,y
        ldaa #'/'
        staa 2,y
        ldaa #'0'+NPAGES/10
        staa 3,y
        ldaa #'0'+NPAGES-NPAGES/10*10
        staa 4,y
        bra rd_out
rd1:    jsr pageptr             ; parameter: "FILTER      SOLO" / "CUTOFF   >    64"
        ldy #LINE1
        ldab #11
        jsr copyn
        ldaa #' '
        staa 0,y
        iny
        jsr corner
        jsr itemptr
        ldab #IT_LABEL
        abx
        ldy #LINE2
        ldab #9
        jsr copyn
        ldaa #' '
        ldab LVL
        cmpb #2
        bne rd1a
        ldaa #'>'
rd1a:   staa 0,y
        iny
        sty VPTR
        jsr fmtval
rd_out: ldd #LINE1
        std LINE1P
        ldd #LINE2
        std LINE2P
        jsr WINFULL
        jmp DRAW

copyn:  ldaa 0,x                ; B bytes X -> Y (both advance)
        staa 0,y
        inx
        iny
        decb
        bne copyn
        rts

corner: ldaa SELP               ; 4 chars at Y: " ALL", or " P2*" (partial 2, on) / " P2 " (off)
        bne cn1
        ldx #s_all
        ldab #4
        jmp copyn
cn1:    ldab #' '
        stab 0,y
        ldab #'P'
        stab 1,y
        tab
        addb #'0'
        stab 2,y
        deca
        ldx #pmask
        tab
        abx
        ldaa 0,x
        anda WORK+$0C
        beq cn2
        ldaa #'*'
        bra cn3
cn2:    ldaa #' '
cn3:    staa 3,y
        rts

partnm: ldaa PARTIX             ; 4-char part name at Y
        asla
        asla
        ldx #pnames
        tab
        abx
        ldab #4
        jmp copyn

; value of IT as 6 chars at VPTR
fmtval: jsr getval
        staa VAL
        ldy VPTR
        ldx IT
        ldab IT_TYPE,x
        cmpb #T_NUM
        bne fv1
        ldab VAL
        clra
        jmp fmtnum
fv1:    cmpb #T_SGN
        bne fv2
        ldab VAL
        subb IT_AUX,x
        beq fv1z
        bmi fv1n
        ldaa #'+'
        jmp fmtnum
fv1n:   negb
        ldaa #'-'
        jmp fmtnum
fv1z:   clra
        jmp fmtnum
fv2:    cmpb #T_PCM
        bne fv3
        ldab VAL                ; "1- 12": bank - wave
        andb #$7F
        incb
        clra
        jsr fmtnum
        ldy VPTR
        ldaa VAL
        rola
        ldaa #'1'
        adca #0
        staa 0,y
        ldaa #'-'
        staa 1,y
        rts
fv3:    ldaa IT_AUX,x           ; list types: 6-char names
        asla
        ldx #listtab
        tab
        abx
        ldx 0,x
        ldaa VAL
        ldab #6
        mul
        abx
        ldab #6
        jmp copyn

; B = number, A = sign char (0 = none): 6 chars right-aligned at Y
fmtnum: staa SIGN
        stab MAGN
        sty T16
        ldx T16
        ldab #6
        ldaa #' '
fn_sp:  staa 0,x
        inx
        decb
        bne fn_sp
        dex
        ldab MAGN
fn_dg:  stx PB
        clra
        ldx #10
        idiv
        addb #'0'
        stx QT
        ldx PB
        stab 0,x
        dex
        ldab QT+1
        bne fn_dg
        ldaa SIGN
        beq fn_x
        staa 0,x
fn_x:   rts

; ---------------- boot ----------------
; called by BOOTCOPY in IC4 with bank 5 + PA6 high: copy the RAM trampoline, then return through BOOTRET in RAM
boot8:  ldx #TRAMP_IMG
        ldy #RAMBASE
        ldab #TRAMP_LEN
        jsr b8_cp
        ldx #HOOK_IMG           ; v0.5: the tempo-LED hooks IC4 jumps to
        ldy #HOOKBASE
        ldab #HOOK_LEN
        jsr b8_cp
        clr EDIT
        clr PARTIX
        ldx #splash             ; ~0.6 s "SYNTH READY": proves the PA6 half switch + boot copy on hardware
        ldy #LINE1
        ldab #32
        jsr copyn
        ldd #LINE1
        std LINE1P
        ldd #LINE2
        std LINE2P
        jsr WINFULL
        jsr DRAW
        ldy #3
        jsr $ED35               ; stock busy delay, Y = 5 is about 1 s
        jmp BOOTRET

b8_cp:  ldaa 0,x                ; B bytes X -> Y
        staa 0,y
        inx
        iny
        decb
        bne b8_cp
        rts

